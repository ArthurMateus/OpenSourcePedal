"""Equiripple FIR halfband coefficients for the HQ oversampler (ADR-0005 D1, D3, D4 and Amendment A2).

Writes dsp-core/src/oversampling/HalfbandFirCoefs.h (generated, do not edit).

Design (P. P. Vaidyanathan, T. Q. Nguyen, "A 'trick' for the design of FIR half-band filters", IEEE Trans. Circuits
and Systems 34(3), 1987): a type-II lowpass g of length 2K with passband [0, 2·fp], designed with scipy.signal.remez,
gives the halfband h of length 4K − 1 with h[2j] = g[j] / 2, h[2K − 1] = 1/2 and every other odd tap 0. Each filter
delays by 2K − 1 samples at its higher rate. D4 needs the total up + down delay of the cascade to be an integer
number of base-rate samples, so for stage s (rate 2^(s+1)·fs) the script picks the smallest K_up, K_down that meet
the attenuation and make (2·K_up − 1 + 2·K_down − 1) a multiple of 2^(s+1).

Usage: python -I tools/design/halfband_fir.py [--check]   (--check: verify the committed header is up to date)
"""

import argparse
import pathlib
import sys

import numpy as np
from scipy import signal

# ADR-0005 D3 FIR column with Amendment A2: (stopband dB, transition) for up and down, per stage (0 = fs <-> 2fs).
# The design attenuation is above the D3 minimum of 100 dB so that the identity null of REQ-OS-001a (passband ripple
# equals stopband ripple in a halfband) reaches -120 dBFS on the test signal.
STAGES = [
    {"up": (110.0, 0.03), "down": (110.0, 0.03)},
    {"up": (110.0, 0.06), "down": (110.0, 0.06)},
    {"up": (110.0, 0.06), "down": (110.0, 0.06)},
]

HEADER = pathlib.Path(__file__).resolve().parents[2] / "dsp-core" / "src" / "oversampling" / "HalfbandFirCoefs.h"


def halfband_g(k: int, fp: float) -> np.ndarray:
    # Type II (even length) forces a zero at Nyquist, so the band [0.5, 0.5] only pins the response there.
    return signal.remez(2 * k, [0.0, 2.0 * fp, 0.5 - 1e-9, 0.5], [1.0, 0.0], fs=1.0)


def stopband_db(g: np.ndarray, fp: float) -> float:
    k = len(g) // 2
    h = np.zeros(4 * k - 1)
    h[0::2] = 0.5 * g
    h[2 * k - 1] = 0.5
    w, resp = signal.freqz(h, worN=1 << 15, fs=1.0)
    return -20.0 * np.log10(np.max(np.abs(resp[w >= 0.5 - fp])))


def smallest_k(att: float, tw: float, start: int = 2) -> int:
    k = start
    while stopband_db(halfband_g(k, 0.25 - tw), 0.25 - tw) < att:
        k += 1
    return k


def design() -> list[dict]:
    stages = []
    for s, spec in enumerate(STAGES):
        ku, kd = smallest_k(*spec["up"]), smallest_k(*spec["down"])
        modulus = 2 ** (s + 1)
        # Grow the cheaper filter one K at a time until the stage delay is an integer at the base rate.
        while (2 * ku - 1 + 2 * kd - 1) % modulus != 0:
            if ku <= kd:
                ku += 1
            else:
                kd += 1
        stages.append(
            {
                "up": halfband_g(ku, 0.25 - spec["up"][1]),
                "down": halfband_g(kd, 0.25 - spec["down"][1]),
                "spec": spec,
                "delay": (2 * ku - 1 + 2 * kd - 1) // modulus,
            }
        )
    return stages


def render(stages: list[dict]) -> str:
    lines = [
        "#pragma once",
        "",
        "// GENERATED by tools/design/halfband_fir.py. Do not edit. Regenerate and commit both together.",
        "// Even-phase taps g (length 2K) of each FIR halfband: h[2j] = g[j] / 2, h[2K - 1] = 1/2, other odd taps 0.",
        "",
        "namespace osp::dsp::fir {",
        "",
    ]
    for s, st in enumerate(stages):
        for kind in ("up", "down"):
            g = st[kind]
            att, tw = st["spec"][kind]
            name = f"k{kind.capitalize()}{s}"
            lines.append(f"// Stage {s} {kind}: {att:.0f} dB design, transition {tw:.2f}, K = {len(g) // 2}.")
            body = ", ".join(f"{v:.9e}f" for v in g)
            lines.append(f"inline constexpr float {name}[] = {{{body}}};")
        lines.append(f"inline constexpr int kStageDelay{s} = {st['delay']}; // up + down, base-rate samples")
        lines.append("")
    lines.append("} // namespace osp::dsp::fir")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed header differs")
    args = parser.parse_args()
    stages = design()
    text = render(stages)
    for s, st in enumerate(stages):
        print(f"stage {s}: K_up {len(st['up']) // 2}, K_down {len(st['down']) // 2}, delay {st['delay']} base samples")
    if args.check:
        if HEADER.read_text(encoding="utf-8") != text:
            print(f"{HEADER} is out of date: run tools/design/halfband_fir.py", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
